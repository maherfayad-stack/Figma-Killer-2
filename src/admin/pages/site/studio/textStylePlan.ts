/**
 * textStylePlan - CT-5: the three style gestures as the edits that write them.
 *
 * Applying, creating and detaching a text or effect style are each ONE gesture
 * that rewrites up to three places in the user's source - the element's
 * `className`, the element's inline `style={{}}`, and (a create) a stylesheet.
 * This module turns a gesture into the `StudioEdit` payloads that do it, using
 * only the edit kinds the writeback already has:
 *
 *   | gesture | edits |
 *   |---|---|
 *   | apply   | `class` (add the style, take off any other of its family) + `style` (strip the inline values the class now owns - an inline value outranks a class, so left in place the click would change nothing) |
 *   | create  | `css` insert/create (the new rule, from the values the layer shows) + `class` (add it) + `style` (strip the inline values it now holds) |
 *   | detach  | `class` (take the style off) + `style` (write its declarations back inline, except the ones the element already set itself) |
 *
 * Every `class` edit carries `restyle: true` (`studioEditSchemas.ts`): the batch
 * is journaled - one undo, byte for byte, a created stylesheet included - and
 * all or nothing, so a refused class edit can never leave the inline values
 * stripped.
 *
 * Planning is pure and runs before anything is posted, so every refusal the
 * CLIENT can know is a sentence next to the control, not a toast after a round
 * trip: a value the element computes in code, a style that changes at a
 * breakpoint (inline values cannot), a layer with no place in the source, a
 * name that is taken. What only the server's AST read can know (an expression
 * `className` it cannot rewrite) comes back as the batch's refusal.
 */
import { hasWritableSourceLocation, isSourceDerivedNodeId, type PageNode, type StyleRule } from '@core/page-tree'
import { camelToKebabCssProperty } from '@core/css-codemods/browser'
import { resolveClassToken, type ClassNameEditToken } from './classNameWriteback'
import { resolveCssInsertDestination } from './styleRuleWriteback'
import type { StructuralEditPayload } from './structuralUndoPlan'
import {
  appliedStyles,
  cssValueText,
  styleProperties,
  type DiscoveredStyle,
  type DiscoveredStyles,
  type StyleFamily,
} from './textStyleDiscovery'

export type RestylePlan =
  | { ok: true; edits: StructuralEditPayload[]; label: string }
  | { ok: false; message: string }

export interface RestyleInput {
  node: PageNode
  styleRules: Readonly<Record<string, StyleRule>>
  /** `discoverStyles(styleRules, …)` - passed in so the planner and the picker agree on what a style is. */
  styles: DiscoveredStyles
  /** `style:<prop>` properties the element computes in code (`lockedStyleProperties`). */
  lockedStyleProps: ReadonlySet<string>
}

const refuse = (message: string): RestylePlan => ({ ok: false, message })

const FAMILY_NAME: Record<StyleFamily, string> = { text: 'text', effect: 'effect' }

function classEdit(nodeId: string, add: ClassNameEditToken[], remove: ClassNameEditToken[]): StructuralEditPayload {
  return { kind: 'class', nodeId, add, remove, restyle: true }
}

/** The element's own place in the source, or the sentence saying it has none. */
function sourceNodeId(node: PageNode): string | RestylePlan {
  if (hasWritableSourceLocation(node.id)) return node.id
  return refuse(
    isSourceDerivedNodeId(node.id)
      ? 'This layer is generated by a loop, so there is no single element in your code to give a style to.'
      : 'This layer is not in your code yet, so there is nothing to give a style to.',
  )
}

function tokenFor(ruleId: string, styleRules: Readonly<Record<string, StyleRule>>): ClassNameEditToken | RestylePlan {
  const resolved = resolveClassToken(ruleId, styleRules as Record<string, StyleRule>, new Map())
  if (resolved === null) return refuse('That style is no longer in your project.')
  if (resolved.kind === 'refused') return refuse(resolved.message)
  if (resolved.kind === 'pending') return refuse('That style has not been saved to a stylesheet yet. Try again in a moment.')
  return resolved.token
}

function isPlan(value: unknown): value is RestylePlan {
  return typeof value === 'object' && value !== null && 'ok' in value
}

/** The inline properties of `node` that are in `properties`. */
function inlineOverlap(node: PageNode, properties: Iterable<string>): string[] {
  const inline = node.inlineStyles ?? {}
  return [...properties].filter((property) => inline[property] !== undefined && inline[property] !== null)
}

function lockedMessage(locked: readonly string[]): string {
  return `${locked.join(', ')} ${locked.length === 1 ? 'is' : 'are'} computed in this layer's code, so Studio cannot change ${locked.length === 1 ? 'it' : 'them'} from here.`
}

/** Apply `style` to the element: its class on, the family's other styles off, the inline values it owns stripped. */
export function planApplyStyle(input: RestyleInput, style: DiscoveredStyle): RestylePlan {
  const nodeId = sourceNodeId(input.node)
  if (isPlan(nodeId)) return nodeId

  const current = appliedStyles(input.styles, style.family, input.node.classIds)
  const add: ClassNameEditToken[] = []
  const remove: ClassNameEditToken[] = []
  if (!current.some((candidate) => candidate.ruleId === style.ruleId)) {
    const token = tokenFor(style.ruleId, input.styleRules)
    if (isPlan(token)) return token
    add.push(token)
  }
  for (const other of current) {
    if (other.ruleId === style.ruleId) continue
    const token = tokenFor(other.ruleId, input.styleRules)
    if (isPlan(token)) return token
    remove.push(token)
  }

  const masked = inlineOverlap(input.node, Object.keys(style.declarations))
  const locked = masked.filter((property) => input.lockedStyleProps.has(property))
  if (locked.length > 0) return refuse(lockedMessage(locked))

  const edits: StructuralEditPayload[] = []
  if (add.length > 0 || remove.length > 0) edits.push(classEdit(nodeId, add, remove))
  if (masked.length > 0) edits.push({ kind: 'style', nodeId, style: {}, remove: masked })
  return { ok: true, edits, label: `Apply ${style.label}` }
}

/** Take `style` off the element and write its declarations back as the element's own inline values. */
export function planDetachStyle(input: RestyleInput, style: DiscoveredStyle): RestylePlan {
  const nodeId = sourceNodeId(input.node)
  if (isPlan(nodeId)) return nodeId
  if (style.hasContextOverrides) {
    return refuse(`${style.label} also changes at some breakpoints, and inline styles cannot. Edit the style's own rule instead.`)
  }
  const token = tokenFor(style.ruleId, input.styleRules)
  if (isPlan(token)) return token

  const inline = input.node.inlineStyles ?? {}
  const inlineValues: Record<string, string> = {}
  for (const [property, value] of Object.entries(style.declarations)) {
    // The element's own value already outranked the class; it keeps it.
    if (inline[property] !== undefined && inline[property] !== null) continue
    if (input.lockedStyleProps.has(property)) continue
    inlineValues[property] = value
  }

  const edits: StructuralEditPayload[] = [classEdit(nodeId, [], [token])]
  if (Object.keys(inlineValues).length > 0) edits.push({ kind: 'style', nodeId, style: inlineValues })
  return { ok: true, edits, label: `Detach ${style.label}` }
}

/** `Heading 1` -> `heading-1`; empty when nothing usable is left. */
export function styleClassSlug(rawName: string): string {
  return rawName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

/** The class a new style of `family` called `rawName` will have. */
export function styleClassName(family: StyleFamily, rawName: string): string | null {
  const slug = styleClassSlug(rawName)
  return slug === '' ? null : `${FAMILY_NAME[family]}-${slug}`
}

/**
 * What the element shows for `family`, as the declarations a new rule would
 * hold: its classes' base values in cascade order, then its own inline values
 * on top. A property the element computes in code is left out - its value is
 * not in the source to copy.
 */
export function declaredStyleValues(input: RestyleInput, family: StyleFamily): Record<string, string> {
  const values: Record<string, string> = {}
  const properties = styleProperties(family)
  const sources: Array<Record<string, unknown>> = []
  for (const classId of input.node.classIds) {
    const rule = input.styleRules[classId]
    if (rule) sources.push(rule.styles)
  }
  sources.push(input.node.inlineStyles ?? {})
  for (const source of sources) {
    for (const property of properties) {
      if (input.lockedStyleProps.has(property)) continue
      const text = cssValueText(property, source[property])
      if (text !== null) values[property] = text
    }
  }
  return values
}

/** Whether the element has anything to make a style of - the menu item's enabled state, with the reason. */
export function createStyleBlocker(input: RestyleInput, family: StyleFamily): string | null {
  const nodeId = sourceNodeId(input.node)
  if (isPlan(nodeId)) return nodeId.ok ? null : nodeId.message
  if (Object.keys(declaredStyleValues(input, family)).length === 0) {
    return family === 'text'
      ? 'This layer has no font, size, weight or spacing set. Set one, then save it as a style.'
      : 'This layer has no shadow or blur. Add one, then save it as a style.'
  }
  return null
}

/**
 * Save what the element shows as a new style and apply it: the rule goes into
 * the stylesheet Studio already writes new classes to (`resolveCssInsertDestination`,
 * the same answer the class picker uses), the class goes on the element, and the
 * inline values the rule now holds come off it.
 */
export function planCreateStyle(input: RestyleInput, family: StyleFamily, rawName: string): RestylePlan {
  const nodeId = sourceNodeId(input.node)
  if (isPlan(nodeId)) return nodeId
  const className = styleClassName(family, rawName)
  if (className === null) return refuse('Give the style a name made of letters or numbers.')
  const taken = Object.values(input.styleRules).some(
    (rule) => rule.kind === 'class' && (rule.name === className || rule.displayName === className),
  )
  if (taken) return refuse(`A class named ${className} already exists. Pick another name, or apply that one.`)

  const declarations = declaredStyleValues(input, family)
  const properties = Object.keys(declarations)
  if (properties.length === 0) return refuse(createStyleBlocker(input, family) ?? 'Nothing to save.')

  const selector = `.${className}`
  const kebab: Record<string, string> = {}
  for (const property of properties) kebab[camelToKebabCssProperty(property)] = declarations[property]!

  // Where the rule goes is the class picker's own answer for a class created on this element.
  const candidate: StyleRule = {
    id: `text-style:${className}`,
    name: className,
    kind: 'class',
    selector,
    order: 0,
    scope: { type: 'node', nodeId: input.node.id, role: 'module-style' },
    styles: {},
    contextStyles: {},
    createdAt: 0,
    updatedAt: 0,
  }
  const destination = resolveCssInsertDestination(candidate, new Map())

  const edits: StructuralEditPayload[] = []
  let token: ClassNameEditToken
  if (destination.kind === 'existing') {
    edits.push({
      kind: 'css',
      op: 'insert',
      nodeId: `css:insert:${destination.file}#${selector}`,
      file: destination.file,
      selector,
      declarations: kebab,
    })
    // A rule inside a CSS Module is reached as `styles.<local>`; anywhere else the class name IS the DOM name.
    token = /\.module\.css$/i.test(destination.file)
      ? { kind: 'module', file: destination.file, local: className }
      : { kind: 'literal', token: className }
  } else {
    // No stylesheet to write into. Without a page the server makes a plain global `studio.css` beside the
    // app entry, so the class is reachable as a literal; with a page it would pick the project's convention
    // (possibly a CSS Module), and the token could not be known here.
    edits.push({ kind: 'css', op: 'create', nodeId: `css:create:${candidate.id}`, selector, declarations: kebab })
    token = { kind: 'literal', token: className }
  }

  const remove: ClassNameEditToken[] = []
  for (const other of appliedStyles(input.styles, family, input.node.classIds)) {
    const otherToken = tokenFor(other.ruleId, input.styleRules)
    if (isPlan(otherToken)) return otherToken
    remove.push(otherToken)
  }
  edits.push(classEdit(nodeId, [token], remove))

  const masked = inlineOverlap(input.node, properties)
  if (masked.length > 0) edits.push({ kind: 'style', nodeId, style: {}, remove: masked })
  return { ok: true, edits, label: `Create ${className}` }
}
